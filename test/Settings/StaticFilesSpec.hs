{-# LANGUAGE NoImplicitPrelude #-}
{-# LANGUAGE OverloadedStrings #-}

module Settings.StaticFilesSpec (spec) where

import qualified Data.ByteString.Lazy as BL
import qualified Data.Text            as T
import           Network.Wai.Test     (simpleBody, simpleHeaders)
import           System.Directory     (doesDirectoryExist, listDirectory)
import           Yesod.Core           (Yesod (addStaticContent), renderRoute)
import           Yesod.EmbeddedStatic (EmbeddedStatic)

import           Settings.StaticFiles  (corydalis_css_bundle_css,
                                       corydalis_js_viewer_js,
                                       corydalis_manifest_json)
import           TestImport

-- | The files that the static subsite serves: those below @static/@,
-- except hidden ones, by their paths relative to it.
staticDirFiles :: IO [FilePath]
staticDirFiles = go "static"
  where
    go dir = do
      names <- sort <$> listDirectory dir
      fmap concat . forM (filter (not . ("." `isPrefixOf`)) names) $ \name -> do
        let path = dir </> name
        isDir <- doesDirectoryExist path
        if isDir
          then go path
          else return [path]

-- | The URL path of a static route, without its query.
staticPath :: Route EmbeddedStatic -> Text
staticPath r = "/static/" <> T.intercalate "/" (fst $ renderRoute r)

spec :: Spec
spec = withApp $ do
  describe "the static subsite" $ do
    it "serves the files under /static/res/" $ do
      liftIO $ staticPath corydalis_manifest_json
        `shouldBe` "/static/res/corydalis/manifest.json"
      get $ StaticR corydalis_manifest_json
      statusIs 200

    it "serves each file in static/ with its contents and type" $ do
      files <- liftIO staticDirFiles
      liftIO $ files `shouldSatisfy` (not . null)
      forM_ files $ \file -> do
        contents <- liftIO $ BL.readFile file
        let rel = fromMaybe file $ stripPrefix "static/" file
        get $ "/static/res/" <> T.pack rel
        statusIs 200
        withResponse $ \response -> liftIO $
          simpleBody response `shouldBe` contents
      get $ StaticR corydalis_css_bundle_css
      assertHeader "Content-Type" "text/css"
      get $ StaticR corydalis_js_viewer_js
      assertHeader "Content-Type" "text/javascript"

    it "serves the fonts that the style sheet refers to" $ do
      css <- liftIO $ readFileUtf8 "static/corydalis/css/bundle.css"
      let fonts = [ T.takeWhile (/= '"') chunk
                  | chunk <- drop 1 (T.splitOn "url(\"../fonts/" css) ]
      liftIO $ fonts `shouldSatisfy` (not . null)
      forM_ fonts $ \font -> do
        -- Relative to the style sheet's URL.
        get $ "/static/res/corydalis/fonts/" <> font
        statusIs 200

    it "returns 404 for missing files" $ do
      get ("/static/res/corydalis/no-such-file.js" :: Text)
      statusIs 404

    it "serves the content generated by widgets" $ do
      result <- runHandler $
        addStaticContent "js" "text/javascript" "var widgetTest = 1;"
      case result of
        Just (Right (route, _)) -> do
          get route
          statusIs 200
          withResponse $ \response -> liftIO $ do
            simpleBody response `shouldSatisfy` (("widgetTest" :: LByteString) `isInfixOf`)
            lookup "Content-Type" (simpleHeaders response)
              `shouldBe` Just "text/javascript"
        other -> liftIO $ expectationFailure $
          "Unexpected addStaticContent result: " <> show other
